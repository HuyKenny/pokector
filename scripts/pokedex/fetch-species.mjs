/**
 * One-time generator: writes app/lib/pokedex/species.ts — the national Pokédex
 * (dex number → English display name) for #1..#1025. Names come from PokeAPI's
 * per-species `names` (proper display: "Mr. Mime", "Farfetch'd", "Flabébé").
 *
 * Run once with Node 22:  node scripts/pokedex/fetch-species.mjs
 * The output is committed as static data (no runtime dependency on PokeAPI).
 */
import { writeFile } from "node:fs/promises";

const MAX_DEX = 1025;
const CONCURRENCY = 16;

async function fetchName(id) {
  const res = await fetch(`https://pokeapi.co/api/v2/pokemon-species/${id}`);
  if (!res.ok) throw new Error(`species ${id}: HTTP ${res.status}`);
  const data = await res.json();
  const en = data.names.find((n) => n.language?.name === "en");
  const name = en?.name ?? data.name;
  return { dex: id, name };
}

async function run() {
  const ids = Array.from({ length: MAX_DEX }, (_, i) => i + 1);
  const out = new Array(MAX_DEX);
  let next = 0;
  async function worker() {
    while (next < ids.length) {
      const idx = next++;
      const id = ids[idx];
      let attempt = 0;
      for (;;) {
        try {
          out[idx] = await fetchName(id);
          break;
        } catch (e) {
          if (++attempt >= 4) throw e;
          await new Promise((r) => setTimeout(r, 500 * attempt));
        }
      }
      if (id % 100 === 0) console.log(`  …${id}/${MAX_DEX}`);
    }
  }
  await Promise.all(Array.from({ length: CONCURRENCY }, worker));

  const rows = out.map((s) => `  { dex: ${s.dex}, name: ${JSON.stringify(s.name)} },`).join("\n");
  const file = `/**
 * National Pokédex #1..#${MAX_DEX} — dex number → English species name.
 * Generated by scripts/pokedex/fetch-species.mjs from PokeAPI. Static data,
 * committed to the repo (no runtime dependency). English names only (consistent
 * with card/set names — see docs/DECISIONS.md D14).
 */

export interface Species {
  dex: number;
  name: string;
}

/** Generation boundaries by last national-dex number (Gen 1..9). */
export const GENERATION_MAX = [151, 251, 386, 493, 649, 721, 809, 905, ${MAX_DEX}] as const;

/** Generation (1-based) for a national dex number. */
export function generationOf(dex: number): number {
  for (let i = 0; i < GENERATION_MAX.length; i++) {
    if (dex <= GENERATION_MAX[i]) return i + 1;
  }
  return GENERATION_MAX.length;
}

export const SPECIES: Species[] = [
${rows}
];
`;
  await writeFile(new URL("../../app/lib/pokedex/species.ts", import.meta.url), file);
  console.log(`Wrote app/lib/pokedex/species.ts (${out.length} species)`);
}

run().catch((e) => {
  console.error(e);
  process.exit(1);
});
